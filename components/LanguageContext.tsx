export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [nativeLanguage, setNativeLanguageState] = useState<NativeLanguage>("vi");

  useEffect(() => {
    try {
      const stored = (localStorage.getItem("nq_native_language") || localStorage.getItem("nihonquest_native_language")) as NativeLanguage | null;
      if (stored && SUPPORTED_LANGUAGES.some((l) => l.code === stored)) {
        setNativeLanguageState(stored);
      }
    } catch {
      // Ignore
    }
  }, []);

  const setNativeLanguage = useCallback((lang: NativeLanguage) => {
    setNativeLanguageState(lang);
    try {
      localStorage.setItem("nq_native_language", lang);
      localStorage.setItem("nihonquest_native_language", lang);
      document.cookie = `nq_native_language=${lang}; path=/; max-age=31536000; SameSite=Lax`;
      if (typeof window !== "undefined") {
        window.dispatchEvent(new CustomEvent("nq:language-changed", { detail: { lang } }));
      }
    } catch {
      // Ignore
    }
  }, []);

  const langInfo =
    SUPPORTED_LANGUAGES.find((l) => l.code === nativeLanguage) || SUPPORTED_LANGUAGES[0];

  const t = useCallback(
    (key: string): string => {
      return (
        EXTENDED_DICTIONARY[nativeLanguage]?.[key] ||
        DICTIONARY[nativeLanguage]?.[key] ||
        EXTENDED_DICTIONARY.vi[key] ||
        DICTIONARY.vi[key] ||
        EXTENDED_DICTIONARY.en[key] ||
        DICTIONARY.en[key] ||
        key
      );
    },
    [nativeLanguage]
  );

  return (
    <LanguageContext.Provider value={{ nativeLanguage, setNativeLanguage, langInfo, t }}>
      {children}
    </LanguageContext.Provider>
  );
}

export function useNativeLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      nativeLanguage: "vi" as NativeLanguage,
      setNativeLanguage: () => {},
      langInfo: SUPPORTED_LANGUAGES[0],
      t: (key: string) => EXTENDED_DICTIONARY.vi[key] || DICTIONARY.vi[key] || key,
    };
  }
  return ctx;
}
